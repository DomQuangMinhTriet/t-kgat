"""Relation report of a built Last-FM KG and the ``pruned`` variant (decision 0016 item 8, plan step B2.5).

    python scripts/14_relation_report.py --data configs/data/lastfm_w3.yaml
    python scripts/14_relation_report.py --data configs/data/lastfm_w3.yaml --write-pruned

Reads ``<processed_dir>/kg/default`` (script 06) and writes ``docs/relation-report-<run_name>.md`` and
``results/relation_report_<run_name>.csv``. With ``--write-pruned`` it also writes ``<processed_dir>/kg/pruned``, the KG
without the relations that cover fewer than 5% of the items or have fewer than 1,000 triples at t1. The script reads the
KG files only: no interaction file and no score.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from tkgat.kg.prune import (  # noqa: E402
    MIN_ITEM_SHARE,
    MIN_TRIPLES,
    prune_rule,
    relation_table,
    write_pruned,
)
from tkgat.pipeline.build import load_config  # noqa: E402


def markdown(run: str, t1: pd.DataFrame, t2: pd.DataFrame, keep: pd.Series) -> str:
    lines = [
        f"# Relation report — {run}",
        "",
        "Generated by `scripts/14_relation_report.py` from `kg/default` (script 06). Do not edit by hand.",
        f"Rule (decision 0016 item 8): drop a relation with item share < {MIN_ITEM_SHARE:.0%} **or** triples < "
        f"{MIN_TRIPLES:,} at t1.",
        "",
        "| relation | triples t1 | triples t2 | items reached | item share | dated | dated share | tails | keep |",
        "|---|---:|---:|---:|---:|---:|---:|---:|:--:|",
    ]
    for (_, a), (_, b), k in zip(t1.iterrows(), t2.iterrows(), keep, strict=True):
        lines.append(
            f"| {a['name']} | {a['triples']:,} | {b['triples']:,} | {a['items']:,} | {a['item_share']:.1%} | "
            f"{a['dated']:,} | {a['dated_share']:.1%} | {a['tails']:,} | {'yes' if k else 'no'} |"
        )
    kept = int(t1.loc[keep, "triples"].sum())
    total = int(t1["triples"].sum())
    lines += [
        "",
        f"Kept: {int(keep.sum())} of {len(t1)} relations, {kept:,} of {total:,} triples at t1 ({kept / total:.1%}).",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--write-pruned", action="store_true")
    args = ap.parse_args()
    cfg = load_config(args.data)
    run = cfg.get("run_name", cfg["name"])
    kg_dir = Path(cfg["processed_dir"]) / "kg" / "default"
    t1, t2 = relation_table(kg_dir, "t1"), relation_table(kg_dir, "t2")
    keep = prune_rule(t1)
    out_md = ROOT / "docs" / f"relation-report-{run}.md"
    out_md.write_text(markdown(run, t1, t2, keep), encoding="utf-8")
    t1.assign(keep=keep).to_csv(ROOT / "results" / f"relation_report_{run}.csv", index=False)
    print(f"wrote {out_md}; keep {list(t1.loc[keep, 'name'])}, drop {list(t1.loc[~keep, 'name'])}")
    if args.write_pruned:
        info = write_pruned(kg_dir, kg_dir.parent / "pruned", list(t1.loc[~keep, "name"]))
        print(f"wrote {kg_dir.parent / 'pruned'}: {info['n_relations']} relations, triples {info['n_triples']}")


if __name__ == "__main__":
    main()
