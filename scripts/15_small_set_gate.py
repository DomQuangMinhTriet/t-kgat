"""Small-set gate of decision 0016 (item 9): the evidence for items 5, 6 and 8, from validation rows only.

    python scripts/15_small_set_gate.py
    python scripts/15_small_set_gate.py --data configs/data/lastfm_w2.yaml --out /tmp/gate.md

Reads the **validation** rows of ``results/registry.csv`` for the run name of the small set (``lastfm-w3``), the history
files of those runs (``results/runs/lastfm-w3/``), ``data/processed/<run>/meta.json`` and the KG ``kg_meta.json`` files,
and writes ``docs/small-set-gate.md``. The rules (``tkgat.analysis.gate``) are applied mechanically and the numbers they
used are printed next to each verdict. No test score is read and nothing from the small set is a result.

Model files of the small set are named ``<model>_w3_<schedule>.yaml`` (``configs/model/small/``): ``bprmf``, ``kgat``,
``kgat_nokg``, ``kgat_pruned`` and the schedule ``none`` or ``cosine``.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from tkgat import registry  # noqa: E402
from tkgat.analysis import gate  # noqa: E402
from tkgat.pipeline.build import load_config  # noqa: E402

TAG = re.compile(r"^(?P<model>bprmf|kgat_nokg|kgat_pruned|kgat)_w\d_(?P<schedule>none|cosine)$")
SCHEDULE_KEYS = ("lr_schedule", "lr_final_ratio")


def load_epoch_script():
    spec = importlib.util.spec_from_file_location("epoch_budget", ROOT / "scripts" / "13_epoch_budget.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def split_tag(tag: str) -> tuple[str, str] | None:
    m = TAG.match(tag)
    return (m["model"], m["schedule"]) if m else None


def val_results(reg: pd.DataFrame, run: str) -> pd.DataFrame:
    """Validation rows of the small set in the shape ``tkgat.analysis.gate`` expects."""
    rows = []
    for _, r in reg[(reg["dataset"] == run) & (reg["phase"] == "val")].iterrows():
        parsed = split_tag(r["model"])
        if parsed is None:
            continue
        cfg = {k: v for k, v in json.loads(r["config"]).items() if k not in SCHEDULE_KEYS}
        rows.append(
            {
                "model": parsed[0],
                "schedule": parsed[1],
                "point": json.dumps(cfg, sort_keys=True),
                "lr": cfg["lr"],
                "seed": int(r["seed"]),
                gate.METRIC: float(r[gate.METRIC]),
                "ndcg@20": float(r["ndcg@20"]),
                "best_epoch": float(r["best_epoch"]),
                "seconds": float(r["seconds"]),
            }
        )
    return pd.DataFrame(rows)


def n(x, digits: int = 4) -> str:
    return "–" if x is None or pd.isna(x) else f"{x:.{digits}f}"


def table_lines(header: list[str], rows: list[list[str]]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"] + [
        "| " + " | ".join(r) + " |" for r in rows
    ]


def markdown(run: str, results: pd.DataFrame, runs: pd.DataFrame, meta: dict, kg: dict) -> str:
    out = [
        f"# Small-set gate — {run}",
        "",
        "Generated by `scripts/15_small_set_gate.py` from validation rows of `results/registry.csv` and the history "
        "files of the small set. Do not edit by hand. **Nothing here is a result**: the small set only chooses "
        "protocol options (decision 0016 item 9). No test score is read.",
        "",
        "## The set",
        "",
        f"- Window: last {meta['clean']['time_window']['window_months']} months of the pair set; "
        f"{meta['clean']['time_window']['ratings_kept']:,} pairs before the split.",
        f"- After the split and the 5-core: {meta['n_users']:,} users, {meta['n_items']:,} items, "
        f"{meta['train_pos']:,} train and {meta['val_pos']:,} validation positives.",
        f"- KG at t1: default {kg['default']:,} triples"
        + (f", pruned {kg['pruned']:,} triples." if "pruned" in kg else ", pruned: not built."),
        "",
    ]
    if results.empty:
        return "\n".join(out + ["No validation row of the small set in the registry yet.", ""])
    points = gate.best_points(results)
    extra = results.groupby(["model", "schedule", "point"]).agg(
        ndcg=("ndcg@20", "mean"), epoch=("best_epoch", "median"), sec=("seconds", "median")
    )
    out += ["## Validation by model, schedule and grid point (mean over seeds)", ""]
    rows = []
    for _, p in points.iterrows():
        e = extra.loc[(p["model"], p["schedule"], p["point"])]
        rows.append(
            [
                p["model"],
                p["schedule"],
                f"`{p['point']}`",
                str(int(p["seeds"])),
                n(p["mean"]),
                n(p["std"]),
                n(e["ndcg"]),
                n(e["epoch"], 0),
                n(e["sec"], 0),
                "**best**" if p["best"] else "",
            ]
        )
    out += table_lines(
        [
            "model",
            "schedule",
            "grid point",
            "seeds",
            "val Recall@20",
            "std",
            "val NDCG@20",
            "median best epoch",
            "s/run",
            "",
        ],
        rows,
    )
    verdicts = {
        "schedule": gate.schedule_verdict(points),
        "lr 1e-4": gate.lr_verdict(points),
        "pruned": gate.pruned_verdict(points, kg) if "pruned" in kg else {"verdict": "pending", "rows": []},
        "KGAT vs KGAT without KG": gate.gate_verdict(points),
    }
    chosen = verdicts["schedule"]["verdict"]
    budget_models = tuple(m for m in ("kgat", "kgat_nokg", "kgat_pruned"))
    if not runs.empty:
        runs = runs.assign(
            schedule=runs["model"].map(lambda t: (split_tag(t) or (None, None))[1]),
            model=runs["model"].map(lambda t: (split_tag(t) or (t, None))[0]),
        )
        if chosen in ("cosine", "none"):
            runs = runs[runs["schedule"] == chosen]
        verdicts["epoch budget"] = gate.epoch_budget(runs, budget_models)
    else:
        verdicts["epoch budget"] = {"verdict": "pending", "rows": []}
    out += ["", "## Verdicts (rules of `tkgat.analysis.gate`, fixed before the KGAT runs)", ""]
    for name, v in verdicts.items():
        out += [f"### {name}: **{v['verdict']}**", ""]
        if v["rows"]:
            cols = list(v["rows"][0])
            out += table_lines(
                cols, [[n(r[c]) if isinstance(r[c], float) else str(r[c]) for c in cols] for r in v["rows"]]
            )
        else:
            out.append("Not enough rows yet.")
        out.append("")
    out += [
        "## What this does not decide",
        "",
        "- The gamma and tau values of the T-KGAT grid (0016 item 7) need the combined model on the small set.",
        "- The relations with delta_kg = 1 (item 7) come from `docs/relation-report-*.md` and are fixed in 0016.",
        "- `window_months` (3 or 2) is decided by the seconds per epoch of KGAT measured on the machine that will "
        "run it (`scripts/measure_kgat.py`), not by a score.",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="configs/data/lastfm_w3.yaml")
    ap.add_argument("--registry", default="results/registry.csv")
    ap.add_argument("--runs-dir", default="results/runs")
    ap.add_argument("--out", default="docs/small-set-gate.md")
    args = ap.parse_args(argv)

    cfg = load_config(args.data)
    run = cfg.get("run_name", cfg["name"])
    processed = Path(cfg["processed_dir"])
    meta = json.loads((processed / "meta.json").read_text(encoding="utf-8"))
    kg = {}
    for variant in ("default", "pruned"):
        path = processed / "kg" / variant / "kg_meta.json"
        if path.exists():
            kg[variant] = int(json.loads(path.read_text(encoding="utf-8"))["n_triples"]["t1"])
    reg = registry.load(args.registry) if Path(args.registry).exists() else pd.DataFrame(columns=registry.FIELDS)
    results = val_results(reg, run)
    runs = load_epoch_script().collect(Path(args.runs_dir), [run])
    Path(args.out).write_text(markdown(run, results, runs, meta, kg), encoding="utf-8", newline="\n")
    print(f"{len(results)} validation rows -> {args.out}")


if __name__ == "__main__":
    main()
